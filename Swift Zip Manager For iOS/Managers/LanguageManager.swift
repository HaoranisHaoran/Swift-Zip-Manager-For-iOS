    func localizedString(_ key: String, language: String) -> String {
        let langCode = String(language.prefix(2))
        
        if let translation = translations[language]?[key] {
            return translation
        }
        
        if let translation = translations[langCode]?[key] {
            return translation
        }
        
        return translations["en"]?[key] ?? key
    }
}

// MARK: - String Extension
extension String {
    func localized(with manager: LanguageManager) -> String {
        return LocalizationService.shared.localizedString(self, language: manager.currentLanguage)
    }
}
