import SwiftUI
import Combine

class LanguageManager: ObservableObject {
    @Published var currentLanguage: String = "en"
    
    let supportedLanguages: [String: String] = [
        "en": "English",
        "zh-Hans": "简体中文",
        "zh-Hant": "繁體中文",
        "ja": "日本語",
        "ko": "한국어",
        "fr": "Français",
        "de": "Deutsch",
        "es": "Español",
        "it": "Italiano",
        "pt": "Português",
        "ru": "Русский",
        "ar": "العربية",
        "tr": "Türkçe",
        "vi": "Tiếng Việt"
    ]
    
    init() {
        if let preferredLang = Locale.preferredLanguages.first {
            let langCode = String(preferredLang.prefix(2))
            if supportedLanguages.keys.contains(where: { $0.hasPrefix(langCode) }) {
                currentLanguage = supportedLanguages.keys.first { $0.hasPrefix(langCode) } ?? "en"
            }
        }
        
        if let savedLang = UserDefaults.standard.string(forKey: "AppLanguage"),
           supportedLanguages.keys.contains(savedLang) {
            currentLanguage = savedLang
        }
    }
    
    func setLanguage(_ language: String) {
        currentLanguage = language
        UserDefaults.standard.set(language, forKey: "AppLanguage")
        UserDefaults.standard.synchronize()
    }
    
    func localizedString(_ key: String) -> String {
        return LocalizationService.shared.localizedString(key, language: currentLanguage)
    }
}

